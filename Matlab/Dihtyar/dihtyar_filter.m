function s = dihtyar_filter(v, k, l, m1, m2)
% Ôóíêöèÿ öèôğîâîé ôèëüòğàöèè: Ìîäèôèöèğîâàííûé cusp-like ôèëüòğ 
% Âõîäíûå äàííûå: v - èñõîäíûé ñèãíàë, k, l, m1, m2 - ïàğàìåòğû ôèëüòğà
% Âûõîäíûå äàííûå: s - îòôèëüòğîâàííûé ñèãíàë

    N = length(v); % Óçíàåì, ñêîëüêî âñåãî òî÷åê â íàøåì ñèãíàëå
    
    % Ñîçäàåì ïóñòûå ìàññèâû äëÿ ïğîìåæóòî÷íûõ ğàñ÷åòîâ, çàïîëíåííûå íóëÿìè
    dk = zeros(1, N);
    d1 = zeros(1, N);
    p  = zeros(1, N);
    q  = zeros(1, N);
    s  = zeros(1, N);

    % Çàïóñêàåì öèêë ïî âñåì òî÷êàì ñèãíàëà îò 1 äî N
    for n = 1:N
        % 1. Ñ÷èòàåì dk(n) = v(n) - v(n-k)
        if (n - k) >= 1
            dk(n) = v(n) - v(n-k);
        else
            dk(n) = v(n); % Åñëè âûøëè çà ïğåäåëû ìàññèâà ñëåâà, ñ÷èòàåì v(n-k) ğàâíûì 0
        end
        
        % 2. Ñ÷èòàåì d1(n) = v(n) - v(n-1)
        if (n - 1) >= 1
            d1(n) = v(n) - v(n-1);
        else
            d1(n) = v(n); % Åñëè âûøëè çà ïğåäåëû ìàññèâà ñëåâà, ñ÷èòàåì v(n-1) ğàâíûì 0
        end
        
        % 3. Ñ÷èòàåì p(n) = p(n-1) + dk(n) - k * d1(n-l)
        term1 = 0;
        if (n - 1) >= 1
            term1 = p(n-1);
        end
        
        term2 = 0;
        if (n - l) >= 1
            term2 = d1(n-l);
        end
        
        p(n) = term1 + dk(n) - k * term2;
        
        % 4. Ñ÷èòàåì q(n) = q(n-1) + m2 * p(n)
        term3 = 0;
        if (n - 1) >= 1
            term3 = q(n-1);
        end
        q(n) = term3 + m2 * p(n);
        
        % 5. Ñ÷èòàåì ôèíàëüíûé ñèãíàë s(n) = s(n-1) + q(n) + m1 * p(n)
        term4 = 0;
        if (n - 1) >= 1
            term4 = s(n-1);
        end
        s(n) = term4 + q(n) + m1 * p(n);
    end
end
