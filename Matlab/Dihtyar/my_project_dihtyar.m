% Главный проект для выполнения Задания №1 (Вариант 3)
clear; % Очищает память от старых переменных
clc;   % Очищает командное окно

% ========================================================
% ЧАСТЬ 1 и 2: Исходный сигнал
% ========================================================
A = 1;       % Амплитуда
tau1 = 16;   % Параметр тау_1
tau2 = 5;    % Параметр тау_2

% Создаем массив времени t от -10 до 100 с шагом 1
t = -10:1:100; 

% Вызываем функцию dihtyar_signal для генерации массива чисел y
y = dihtyar_signal(t, A, tau1, tau2);

% Строим первый график (исходный сигнал)
figure(1); % Окно для первого графика
plot(t, y, 'b-', 'LineWidth', 2); % Синяя линия
grid on;   
xlabel('Время (t)');
ylabel('Сигнал (y)');
title('Исходный экспоненциальный сигнал');

% ========================================================
% ЧАСТЬ 3: Фильтрация (Вариант 3: cusp-like фильтр)
% ========================================================
% Задаем параметры фильтра из таблицы для Варианта 3
l_param  = 5;   % Параметр l (для варианта 3 равен 5)
k_param  = 11;  % Параметр k (для варианта 3 равен 11)
m1_param = 16;  % Параметр m1
m2_param = 1;   % Параметр m2

% Запускаем наш цифровой фильтр
y_filtered = dihtyar_filter(y, k_param, l_param, m1_param, m2_param);

% Строим второй график (отфильтрованный сигнал)
figure(2); % Отдельное новое окно для второго графика
plot(t, y_filtered, 'r-', 'LineWidth', 2); % Рисуем красной линией
grid on;
xlabel('Время (t)');
ylabel('Сигнал после фильтра (s)');
title('Отфильтрованный сигнал (Вариант 3)');
