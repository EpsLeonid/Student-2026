clear;
% Данная команда удаляет все переменные из рабочей памяти.
% Это нужно, чтобы в памяти не остались значения от предыдущих запусков,
% иначе они могут случайно повлиять на результат.

clc;
% Команда очищает окно Command Window, чтобы
% предыдущие сообщения и результаты не смешивались с новыми.

close all;
% Команда закрывает все ранее открытые графические окна.

% ============================================================
% Параметры сигнала (задание 1 и 2)
% ============================================================

A = 1;
tau1 = 16;
tau2 = 5;

% Формирую массив моментов времени от -10 до 100 с шагом 1.
t = (-10:1:100)';   

% Вызываю функцию из задания 1, которая считает сигнал по формуле.
% Результат сохраняю в переменную v, так как в формулах задания 3
% входной сигнал обозначен буквой v.
v = my_function_Milovanova(t, A, tau1, tau2);

% ============================================================
% Параметры треугольного фильтра (задание 3)
% ============================================================

k = 6;
l = 6;
M = 16;

% Вызываю функцию из задания 3, которая по формулам Б превращает
% входной сигнал v в выходной сигнал s.
% Функция возвращает четыре массива: s, p, r, d.
% Все они нужны для построения графиков.
[s, p, r, d] = triangular_filter_Milovanova(v, k, l, M);

% ============================================================
% Графики
% ============================================================

% Создаю новое окно для графиков.
figure;

% --- График 1: входной сигнал v(t) ---

% subplot(2,2,1) разбивает окно на 4 области (2 строки, 2 столбца).
subplot(2,2,1);

% Строю график входного сигнала v(t). Параметр 'g-' означает зелёный
% цвет линии, 'LineWidth', 1.5 - толщина линии.
plot(t, v, 'g-', 'LineWidth', 1.5);

% Сетка на графике.
grid on;

% Подписываю оси: по горизонтали - время t, по вертикали - значение v(t).
xlabel('t'); ylabel('v(t)');

% Заголовок первого графика:
title('Входной сигнал v(n)');

% --- График 2: выходной сигнал s(t) ---

% Аналогично для второго графика:
subplot(2,2,2);
plot(t, s, 'm-', 'LineWidth', 1.5);
grid on;
xlabel('t'); ylabel('s(n)');
title('Выходной сигнал s(n)');

% Сохраняю окно со всеми графиками в один файл.
saveas(gcf, 'graphs_Milovanova.jpg');
