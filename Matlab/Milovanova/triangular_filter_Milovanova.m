function [s, p, r, d] = triangular_filter_Milovanova(v, k, l, M)
% Преобразую входной сигнал v (массив значений, полученный из задания 1)
% в треугольный фильтр по формулам Б (5 вариант).
% k, l, M - входные параметры.
% На выходе должно получиться четыре массива s, p, r, d.

% Преобразую вектор v в вектор-столбец, так как дальше идёт работа
% с индексами и сдвигами элементов.
v = v(:);

% N - это количество отсчётов сигнала, оно необходимо для того, 
% чтобы не выйти за границы массива при сдвиге. 
N = length(v);

% Создаю три массива из нулей, каждый длиной N:
%   vk - будет хранить v(n-k), то есть сигнал, сдвинутый на k отсчётов,
%   vl - будет хранить v(n-l), сдвиг на l отсчётов,
%   vkl - будет хранить v(n-k-l), сдвиг на k+l отсчётов.
vk  = zeros(N,1);
vl  = zeros(N,1);
vkl = zeros(N,1);

% Реализую сдвиг сигнала на k отсчётов вправо.
% Первые k элементов vk остаются нулями,
% а начиная с позиции k+1 копирую значения v с самого начала.
% Условие if k < N нужно, чтобы не выйти за пределы массива:
% если задержка k больше длины сигнала, весь vk останется нулевым.
if k < N
    vk(k+1:N) = v(1:N-k);  
end

% Аналогичный сдвиг на l отсчётов, только с другой задержкой.    
if l < N
    vl(l+1:N) = v(1:N-l);
end

% Сдвиг на k+l отсчётов, понадобится в формуле.    
if (k+l) < N
    vkl(k+l+1:N) = v(1:N-k-l);
end

% Считаю сигнал d(n) по формуле d(n) = v(n) - v(n-k) - v(n-l) + v(n-k-l).
% Вычитание и сложение выполняются поэлементно, так как все четыре
% массива имеют одинаковый размер.
d = v - vk - vl + vkl;

% cumsum — это встроенная функция, возвращающая накопленную 
% сумму элементов массива.
p = cumsum(d);

% Считаю сигнал r(n) по формуле. Оператор .* - поэлементное умножение:
% каждый элемент d умножается на M, потому что M - это число, а d - массив.
r = p + M .* d;

% Использую cumsum, чтобы получить выходной сигнал s(n) по формуле, 
% где s - это накопленная сумма значений r.
s = cumsum(r);

end