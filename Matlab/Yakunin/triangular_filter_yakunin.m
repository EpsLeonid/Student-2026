function s = triangular_filter(v, k, l, M)
% ВХОДНЫЕ ПАРАМЕТРЫ:
%   v - вектор отсчетов оцифрованного входного импульса y(t)
%   k - параметр задержки первого блока дифференцирования (для вар. 8: k = 7)
%   l - параметр задержки второго блока дифференцирования (для вар. 8: l = 7)
%   M - коэффициент компенсации постоянной времени спада tau (для вар. 8: M = 16)
%
% ВЫХОДНОЙ ПАРАМЕТР:
%   s - итоговый отфильтрованный сигнал s(n)

    % Число обрабатываемых отсчетов
    N = length(v);

    % Предварительное выделение памяти под массивы для ускорения вычислений и задание нулевых начальных условий для n < 0
    d = zeros(1, N);  % Массив двойной разности d^{k,l}(n)
    p = zeros(1, N);  % Массив первого накопителя 
    r = zeros(1, N);  % Промежуточный сигнал после десвертки
    s = zeros(1, N);  % Выходной сигнал после второго накопителя

    % Рекурсивная пошаговая фильтрация в реальном времени
    for n = 1:N
        % -------------------------------------------------------------
        % Шаг 1: Вычисление d^{k,l}(n) по уравнению (1) статьи:
        % Два последовательных блока дифференцирования (DS-блока)
        % -------------------------------------------------------------
        v_curr = v(n);
        
        % Учет запаздывания на k отсчетов (если n-k < 1, значение равно 0):
        if (n - k >= 1)
            v_k = v(n - k);
        else
            v_k = 0;
        end
        
        % Учет запаздывания на l отсчетов:
        if (n - l >= 1)
            v_l = v(n - l);
        else
            v_l = 0;
        end
        
        % Учет суммарного запаздывания на (k+l) отсчетов:
        if (n - k - l >= 1)
            v_kl = v(n - k - l);
        else
            v_kl = 0;
        end
        
        % Вторая разность выделяет изменения входного сигнала:
        d(n) = v_curr - v_k - v_l + v_kl;

        % -------------------------------------------------------------
        % Шаг 2: Первый цифровой интегратор:
        % p(n) = p(n-1) + d^{k,l}(n), n >= 0
        % -------------------------------------------------------------
        if (n - 1 >= 1)
            p_prev = p(n - 1);
            s_prev = s(n - 1);
        else
            p_prev = 0;
            s_prev = 0;
        end
        p(n) = p_prev + d(n);

        % -------------------------------------------------------------
        % Шаг 3: Десвертка / компенсация спада:
        % r(n) = p(n) + M * d^{k,l}(n)
        % Слагаемое M*d(n) компенсирует экспоненциальный спад exp(-t/16)
        % -------------------------------------------------------------
        r(n) = p(n) + M * d(n);

        % -------------------------------------------------------------
        % Шаг 4: Второй цифровой интегратор:
        % s(n) = s(n-1) + r(n), n >= 0
        % Интегрирует сигнал r(n), формируя треугольный импульс
        % -------------------------------------------------------------
        s(n) = s_prev + r(n);
    end
end