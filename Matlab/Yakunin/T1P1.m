clear;      % Очистка рабочей области переменных (Workspace)
clc;        % Очистка командного окна (Command Window)
close all;  % Закрытие всех ранее открытых окон графиков

%% Задание 1 и Задание 2: Генерация сигнала и построение графика
% Параметры сигнала по условию задания 1 и 2:
A = 1;          % Амплитуда сигнала
tau1 = 16;      % Постоянная времени спада tau1
tau2 = 5;       % Постоянная времени нарастания tau2

% Вектор времени t от -10 до 100 с шагом 1
t = -10:1:100;

% Вызов m-функции генерации исходного сигнала y(t)
y = generate_signal(t, A, tau1, tau2);

% Построение графика исходного сигнала (Задание 2)
figure(1);
plot(t, y, 'b-', 'LineWidth', 1.5); % Синяя сплошная линия
grid on;                            % Включение координатной сетки
xlabel('Время t');                  % Подпись оси абсцисс
ylabel('Амплитуда y(t)');           % Подпись оси ординат
title('Задание 2: Исходный аналитический импульс y(t)'); % Название графика
legend('y(t) при \tau_1=16, \tau_2=5');