function s = filter_Arhipova(v, k, l, M );

% Реализует преобразование сигнала по формулам варианта Б (Трапецеидальный фильтр).

% Входные параметры:
%   v   - входной дискретный сигнал (массив v(n))
%   k   - параметр задержки (в отсчетах), по условию k=8
%   l   - параметр задержки (в отсчетах), по условию l=5
%   M   - коэффициент усиления/масштабирования, по условию M=16

% Выходные параметры:
%   s - финальный отфильтрованный сигнал s(n)


%   1. d_kl(n) = v(n) - v(n-k) - v(n-l) + v(n-k-l)
%      Это разностный оператор, выделяющий определенные участки сигнала.
%   2. p(n) = p(n-1) + d_kl(n)
%      Накопитель (интегратор) разностного сигнала.
%   3. r(n) = p(n) + M * d_kl(n)
%      Комбинация накопленного и текущего разностного сигнала.
%   4. s(n) = s(n-1) + r(n)
%      Второй накопитель, формирующий итоговый сигнал.

N = length(v); % Количество отсчетов

% Важно заполнить начальные значения нулями, чтобы избежать ошибок индексации
    d_kl = zeros(1, N);
    p = zeros(1, N);
    r = zeros(1, N);
    s = zeros(1, N);
    
% Последовательно обрабатываем каждый отсчет сигнала
for n = 1:N

    % Текущее значение входного сигнала
    v0 = v(n);

    % Значение v(n-k).
    % Если нужного предыдущего отсчета еще нет,
    % считаем его равным нулю.
    if n-k >= 1
        vk = v(n-k);
    else
        vk = 0;
    end

    % Значение v(n-l)
    if n-l >= 1
        vl = v(n-l);
    else
        vl = 0;
    end

    % Значение v(n-k-l)
    if n-k-l >= 1
        vkl = v(n-k-l);
    else
        vkl = 0;
    end

    % Формула:
    % d^(k,l)(n) = v(n) - v(n-k) - v(n-l) + v(n-k-l)
    d(n) = v0 - vk - vl + vkl;

    % p(n) = p(n-1) + d(n)
    if n == 1
        p(n) = d(n);
    else
        p(n) = p(n-1) + d(n);
    end

    % r(n) = p(n) + M*d(n)
    r(n) = p(n) + M*d(n);

    % s(n) = s(n-1) + r(n)
    if n == 1
        s(n) = r(n);
    else
        s(n) = s(n-1) + r(n);
    end
end

